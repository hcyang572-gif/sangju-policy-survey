/* ══════════════════════════════════════════════════════════════════════
   의견조사 — 두 화면이 «함께 쓰는» 상수 한 곳                🩵물결
   ────────────────────────────────────────────────────────────────────
   쓰는 곳
     · 현황/        (양호창님 전용 · 로그인 · 원문·주관식·CSV)
     · t6-status/   (팀원 공유 · 로그인 없음 · 집계 숫자만)

   ⭐ 두 화면이 같은 숫자를 말하게 하려고 «한 파일» 로 모았습니다.
      ⛔ 어느 한쪽에만 값을 적어 두지 마십시오 — 그 순간 두 화면이 다른 말을 합니다.

   ⚠⚠ 대상 인원(target·GOAL)은 «잠정치» 입니다.
      양호창님이 실제 인원을 확정하시면 «이 파일만» 고치시면 됩니다.
      두 화면의 KPI·막대·진행률·안내문이 모두 따라 바뀝니다.
      확정되면 아래 잠정 플래그를 false 로 내리십시오 — 화면에서 「(잠정)」 글자가 사라집니다.
   ══════════════════════════════════════════════════════════════════════ */
(function () {
  "use strict";

  /* ⭐⭐ 조사 기간의 «정본» 은 저장소 루트 config.js 입니다
       (🔵손길이 window.SURVEY_START · window.SURVEY_END 로 둡니다 — 설문지 화면도 그 값을 씁니다).
     같은 사실을 두 곳에 적어 두면 반드시 갈라지므로, 여기서는 «받아서 쓰기만» 합니다.
       · 루트 값이 있으면  → 그 값으로 아래 기간 항목을 «다시 계산» 합니다.
       · 루트 값이 없으면  → 아래 적어 둔 값을 그대로 씁니다(현황 화면만 따로 열어 볼 때).
       · 두 값이 다르면    → console 에 경고를 남깁니다. 조용히 어긋나지 않게.
     ⛔ 이 파일의 기간 값을 «고쳐서» 루트와 다르게 만들지 마십시오. 루트를 고치십시오. */
  var S = {
  /* ⭐⭐ 조사 기간 — «한국시간(KST) 기준» 입니다 (2026-09-11 양호창님 확정).
       2026-09-11(금) 00:00 KST  ~  2026-09-30(수) 24:00 KST · 20일간
       (개시가 09-14 에서 09-11 로 앞당겨졌습니다)

     ⛔⛔ 날짜 계산에 «반드시» 아래 ISO 값을 쓰십시오.
       new Date("2026-09-11") 은 «UTC 자정» 으로 읽혀 한국에서는 오전 9시가 됩니다.
       그러면 개시일 아침에 들어온 응답이 「기간 밖」으로 잡히고, 남은 날수가 하루 어긋납니다.
       +09:00 을 붙인 값만이 한국 자정을 가리킵니다.
     ⚠ 마감ISO 가 «10월 1일 00:00» 인 것은 오타가 아닙니다 —
       「9월 30일 24:00」과 같은 순간이고, 이렇게 적어야 경계 비교가 «미만(<)» 으로 깔끔합니다.
     ⚠ Supabase 의 submitted_at 은 UTC(timestamptz)입니다. 「오늘 들어온 응답」을 셀 때는
       UTC 자정이 아니라 «KST 자정» 을 경계로 삼아야 합니다 — 두 화면 모두
       toLocaleDateString("sv-SE", { timeZone:"Asia/Seoul" }) 로 KST 날짜를 뽑아 비교합니다.
       ⛔ getDate()·toISOString().slice(0,10) 으로 바꾸지 마십시오. 아침 9시 전 응답이
         통째로 「어제」로 잡힙니다. */
  기간시작: "2026-09-11",
  기간끝:   "2026-09-30",
  시작요일: "금",
  마감요일: "수",
  시작ISO:  "2026-09-11T00:00:00+09:00",
  마감ISO:  "2026-10-01T00:00:00+09:00",   // = 2026-09-30 24:00 KST
  총일수:   20,

  잠정: true,          // ← 대상 인원이 확정되면 false. 화면의 「(잠정)」 표기가 사라집니다.
  GOAL: 54,            // 목표 응답 수 = 아래 target 의 합 (12+10+8+24)

  /* 집계 단위(기관).
     ⭐⭐ name 은 supabase/설문조사_260911.sql 의 CHECK 값과 «글자 단위로» 같아야 합니다.
       · 다섯째 값은 '그 밖' 이 아니라 **'그 밖의 부서'** 입니다.
       · 「읍·면·동」의 가운뎃점은 **U+00B7**(바이트 C2 B7)입니다. 다른 가운뎃점
         (U+2027·U+30FB)을 쓰면 글자가 똑같아 보이는데 집계가 갈립니다 — 눈으로는
         절대 못 찾습니다. 복사해서 쓰십시오.
       (2026-09-11 SQL·시안·이 파일 셋을 코드포인트로 대조해 같음을 확인했습니다)

     ⛔ 읍·면·동은 «한 덩어리» 로만 셉니다.
       한 곳에 사회복지 담당이 한두 명뿐이라, 어느 읍면동인지 드러나면 곧 사람이
       특정됩니다. 설문에 그 칸이 없고, 어느 화면에도 만들지 마십시오. */
  기관: [
    { name: "사회복지과",            target: 12, cls: "d0" },
    { name: "노인장애인복지과",      target: 10, cls: "d1" },
    { name: "아이여성행복과",        target: 8,  cls: "d2" },
    { name: "읍·면·동 행정복지센터", target: 24, cls: "d3" },
    { name: "그 밖의 부서",          target: 0,  cls: "d4" }
  ],

  // ⚠ 재식별 방지 — 이 수보다 적은 칸은 «수치도 막대 길이도» 드러내지 않습니다.
  //   (t6-status 는 서버가 이미 뭉개서 주므로, 화면은 그 값을 그대로 옮겨 적습니다)
  최소공개건수: 3,

  // 총 응답이 이보다 적으면 기관별 분해를 아예 보여주지 않습니다(공유 화면 기준).
  기관별공개하한: 5
  };

  /* ── 루트 config.js 의 기간을 받아 다시 계산 ─────────────────────────
     ⚠ 날짜·요일은 «한국시간» 으로 뽑습니다. 보시는 분의 기기 시간대가 어디든
       한국 날짜가 나와야 합니다(getDate()·toISOString() 을 쓰면 어긋납니다). */
  function kstDay(d) {
    try { return d.toLocaleDateString("sv-SE", { timeZone: "Asia/Seoul" }); }
    catch (e) { return d.toISOString().slice(0, 10); }
  }
  function kstDow(d) {
    try { return d.toLocaleDateString("ko-KR", { timeZone: "Asia/Seoul", weekday: "short" }).replace(/[^가-힣]/g, ""); }
    catch (e) { return ""; }
  }

  var st = window.SURVEY_START, en = window.SURVEY_END;
  if (st && en) {
    var a = new Date(st), b = new Date(en);
    if (isFinite(a) && isFinite(b) && b > a) {
      var 시작 = kstDay(a);
      // 마감ISO 는 «다음 날 00:00» 이므로, 사람이 읽는 마감일은 그 «1분 전» 의 날짜입니다.
      var 끝 = kstDay(new Date(b.getTime() - 60000));
      if (시작 !== S.기간시작 || 끝 !== S.기간끝) {
        console.warn("[설문 상수] 기간이 루트 config.js 와 달라 루트 값으로 맞춥니다 — " +
                     "이 파일: " + S.기간시작 + "~" + S.기간끝 + " / 루트: " + 시작 + "~" + 끝);
      }
      S.기간시작 = 시작;
      S.기간끝 = 끝;
      S.시작ISO = st;
      S.마감ISO = en;
      S.시작요일 = kstDow(a) || S.시작요일;
      S.마감요일 = kstDow(new Date(b.getTime() - 60000)) || S.마감요일;
      S.총일수 = Math.round((b.getTime() - a.getTime()) / 86400000);
    }
  }

  window.SURVEY = S;
})();
